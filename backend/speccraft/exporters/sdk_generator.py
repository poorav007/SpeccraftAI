"""Automated TypeScript and Python SDK generator from OpenAPI 3.0 specifications."""

from __future__ import annotations

import io
import re
import zipfile
from typing import Any, Dict, List, Literal, Union

from speccraft.exporters.postman_exporter import HTTP_METHODS_ORDER, parse_openapi_input

SDKLanguage = Literal["typescript", "python"]


def _to_snake_case(name: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9]+", "_", name or "operation").strip("_")
    snake = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", cleaned).lower()
    return snake or "operation"


def _to_camel_case(name: str) -> str:
    parts = [p for p in re.split(r"[^a-zA-Z0-9]+", name or "operation") if p]
    if not parts:
        return "operation"
    return parts[0][0].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def _ts_type(schema: Dict[str, Any]) -> str:
    if not isinstance(schema, dict):
        return "unknown"
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    t = schema.get("type")
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "string":
        return "string"
    if t == "array":
        return f"Array<{_ts_type(schema.get('items') or {})}>"
    if t == "object":
        return "Record<string, unknown>"
    return "unknown"


def _py_type(schema: Dict[str, Any]) -> str:
    if not isinstance(schema, dict):
        return "Any"
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    t = schema.get("type")
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "string":
        return "str"
    if t == "array":
        return f"List[{_py_type(schema.get('items') or {})}]"
    if t == "object":
        return "Dict[str, Any]"
    return "Any"


class SDKGenerator:
    """Generates clean, zero-dependency TypeScript or Python API client SDKs."""

    def generate(
        self,
        spec: Union[Dict[str, Any], str],
        language: SDKLanguage = "typescript",
    ) -> Dict[str, str]:
        """Generate SDK source files (`{filename: content}`) for the requested language."""
        spec_dict = parse_openapi_input(spec)
        if language == "python":
            return {"client.py": self._generate_python(spec_dict)}
        if language == "typescript":
            return {"client.ts": self._generate_typescript(spec_dict)}
        raise ValueError(f"Unsupported SDK language: {language}")

    def to_zip(
        self,
        spec: Union[Dict[str, Any], str],
        language: SDKLanguage = "typescript",
    ) -> bytes:
        """Package generated SDK files into an in-memory ZIP archive."""
        files = self.generate(spec, language=language)
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            for fname, content in files.items():
                zf.writestr(fname, content)
        return buf.getvalue()

    def _generate_typescript(self, spec_dict: Dict[str, Any]) -> str:
        info = spec_dict.get("info") or {}
        schemas = (spec_dict.get("components") or {}).get("schemas") or {}
        paths = spec_dict.get("paths") or {}

        lines: List[str] = [
            f"// Generated by SpecCraft AI for {info.get('title', 'API')} v{info.get('version', '1.0.0')}",
            "",
        ]

        for name in sorted(schemas.keys()):
            schema = schemas.get(name) or {}
            props = schema.get("properties") or {}
            required = set(schema.get("required") or [])
            lines.append(f"export interface {name} {{")
            for prop_name, prop_schema in props.items():
                opt = "" if prop_name in required else "?"
                lines.append(f"  {prop_name}{opt}: {_ts_type(prop_schema)};")
            lines.append("}")
            lines.append("")

        lines.extend(
            [
                "export class SpecCraftClient {",
                '  constructor(private readonly baseUrl: string = "http://localhost:8000") {}',
                "",
                "  private async request<T>(method: string, path: string, body?: unknown): Promise<T> {",
                "    const res = await fetch(`${this.baseUrl.replace(/\\/+$/, '')}${path}`, {",
                "      method,",
                '      headers: body !== undefined ? { "Content-Type": "application/json" } : undefined,',
                "      body: body !== undefined ? JSON.stringify(body) : undefined,",
                "    });",
                '    if (!res.ok) throw new Error(`HTTP ${res.status}: ${await res.text()}`);',
                "    if (res.status === 204) return undefined as T;",
                "    return (await res.json()) as T;",
                "  }",
                "",
            ]
        )

        for raw_path in sorted(paths.keys()):
            path_item = paths.get(raw_path) or {}
            for method in HTTP_METHODS_ORDER:
                op = path_item.get(method)
                if not isinstance(op, dict):
                    continue
                fn_name = _to_camel_case(op.get("operationId") or f"{method}_{raw_path}")
                params = op.get("parameters") or []
                arg_list: List[str] = []
                path_expr = raw_path
                query_params: List[str] = []

                for p in params:
                    if not isinstance(p, dict) or not p.get("name"):
                        continue
                    pname = str(p["name"])
                    ptype = _ts_type(p.get("schema") or {})
                    if p.get("in") == "path":
                        arg_list.append(f"{pname}: {ptype}")
                        path_expr = path_expr.replace(f"{{{pname}}}", f"${{encodeURIComponent(String({pname}))}}")
                    elif p.get("in") == "query":
                        opt = "" if p.get("required") else "?"
                        arg_list.append(f"{pname}{opt}: {ptype}")
                        query_params.append(pname)

                has_body = isinstance(op.get("requestBody"), dict)
                if has_body:
                    body_schema = (
                        (op["requestBody"].get("content") or {})
                        .get("application/json", {})
                        .get("schema", {})
                    )
                    arg_list.append(f"body: {_ts_type(body_schema)}")

                lines.append(f"  async {fn_name}({', '.join(arg_list)}): Promise<unknown> {{")
                if query_params:
                    lines.append("    const qs = new URLSearchParams();")
                    for qp in query_params:
                        lines.append(f"    if ({qp} !== undefined) qs.set({qp!r}, String({qp}));")
                    lines.append("    const suffix = qs.toString() ? `?${qs.toString()}` : '';")
                    lines.append(f"    return this.request('{method.upper()}', `{path_expr}${{suffix}}`{', body' if has_body else ''});")
                else:
                    lines.append(f"    return this.request('{method.upper()}', `{path_expr}`{', body' if has_body else ''});")
                lines.append("  }")
                lines.append("")

        lines.append("}")
        return "\n".join(lines)

    def _generate_python(self, spec_dict: Dict[str, Any]) -> str:
        info = spec_dict.get("info") or {}
        schemas = (spec_dict.get("components") or {}).get("schemas") or {}
        paths = spec_dict.get("paths") or {}

        lines: List[str] = [
            f'"""Generated by SpecCraft AI for {info.get("title", "API")} v{info.get("version", "1.0.0")}."""',
            "",
            "from __future__ import annotations",
            "from typing import Any, Dict, List, Optional",
            "import httpx",
            "from pydantic import BaseModel",
            "",
        ]

        for name in sorted(schemas.keys()):
            schema = schemas.get(name) or {}
            props = schema.get("properties") or {}
            required = set(schema.get("required") or [])
            lines.append(f"class {name}(BaseModel):")
            if not props:
                lines.append("    pass")
            else:
                for prop_name, prop_schema in props.items():
                    py_t = _py_type(prop_schema)
                    if prop_name in required:
                        lines.append(f"    {prop_name}: {py_t}")
                    else:
                        lines.append(f"    {prop_name}: Optional[{py_t}] = None")
            lines.append("")

        lines.extend(
            [
                "class SpecCraftClient:",
                '    """Typed synchronous httpx client."""',
                "",
                '    def __init__(self, base_url: str = "http://localhost:8000", timeout: float = 15.0) -> None:',
                '        self._client = httpx.Client(base_url=base_url.rstrip("/"), timeout=timeout)',
                "",
            ]
        )

        for raw_path in sorted(paths.keys()):
            path_item = paths.get(raw_path) or {}
            for method in HTTP_METHODS_ORDER:
                op = path_item.get(method)
                if not isinstance(op, dict):
                    continue
                fn_name = _to_snake_case(op.get("operationId") or f"{method}_{raw_path}")
                params = op.get("parameters") or []
                req_args: List[str] = []
                opt_args: List[str] = []
                query_names: List[str] = []

                for p in params:
                    if not isinstance(p, dict) or not p.get("name"):
                        continue
                    pname = _to_snake_case(str(p["name"]))
                    ptype = _py_type(p.get("schema") or {})
                    if p.get("in") == "path":
                        req_args.append(f"{pname}: {ptype}")
                    elif p.get("in") == "query":
                        query_names.append((str(p["name"]), pname))
                        if p.get("required"):
                            req_args.append(f"{pname}: {ptype}")
                        else:
                            opt_args.append(f"{pname}: Optional[{ptype}] = None")

                has_body = isinstance(op.get("requestBody"), dict)
                if has_body:
                    body_schema = (
                        (op["requestBody"].get("content") or {})
                        .get("application/json", {})
                        .get("schema", {})
                    )
                    req_args.append(f"body: {_py_type(body_schema)}")

                all_args = ["self", *req_args, *opt_args]
                lines.append(f"    def {fn_name}({', '.join(all_args)}) -> Any:")
                if query_names:
                    lines.append("        params = {")
                    for raw_q, py_q in query_names:
                        lines.append(f"            {raw_q!r}: {py_q},")
                    lines.append("        }")
                    lines.append("        params = {k: v for k, v in params.items() if v is not None}")
                body_arg = (
                    ", json=body.model_dump() if isinstance(body, BaseModel) else body"
                    if has_body
                    else ""
                )
                params_arg = ", params=params" if query_names else ""
                lines.append(
                    f'        resp = self._client.request("{method.upper()}", f"{raw_path}"{params_arg}{body_arg})'
                )
                lines.append("        resp.raise_for_status()")
                lines.append("        return None if resp.status_code == 204 else resp.json()")
                lines.append("")

        return "\n".join(lines)

